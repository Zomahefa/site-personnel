const { chromium } = require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())});
  await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForTimeout(1200);
  console.log('h1', await page.locator('h1').innerText());
  console.log('stats', await page.locator('.hero-stats').innerText());
  await page.evaluate(()=>window.scrollTo({top:document.querySelector('#projets').offsetTop-70,behavior:'instant'}));
  await page.waitForTimeout(1800);
  await page.screenshot({path:'preview/gallery-check-1.png'});
  const gallery = page.locator('.project-gallery').first();
  console.log('gallery visible', await gallery.isVisible());
  console.log('state', await gallery.locator('.gallery-state').innerText());
  await page.waitForTimeout(5200);
  console.log('after5s', await gallery.locator('.gallery-caption').innerText());
  await gallery.hover();
  await page.waitForTimeout(5400);
  console.log('hover state', await gallery.locator('.gallery-state').innerText());
  console.log('hover caption', await gallery.locator('.gallery-caption').innerText());
  await page.screenshot({path:'preview/gallery-check-2.png'});
  console.log('errors', errors);
  await browser.close();
})();
